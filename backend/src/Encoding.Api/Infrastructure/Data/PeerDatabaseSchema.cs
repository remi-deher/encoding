using System.Data.Common;
using System.Collections.Immutable;
using System.Globalization;
using System.Security.Cryptography;
using System.Text.Json;
using Encoding.Api.Infrastructure.Data.Sqlite;

namespace Encoding.Api.Infrastructure.Data;

public sealed record PeerColumn(string Name, string Type, int KeyOrder);
public sealed record PeerTable(string Name, PeerColumn[] Columns, string[] Parents)
{
    public PeerColumn[] Keys => Columns.Where(column => column.KeyOrder > 0).OrderBy(column => column.KeyOrder).ToArray();
}
public sealed record PeerRowChange(string Table, string Operation, Dictionary<string, JsonElement> Key,
    Dictionary<string, JsonElement>? Row);
public sealed record PeerDatabaseImage(long Revision, string Schema, ImmutableDictionary<string, ImmutableDictionary<string, Dictionary<string, JsonElement>>> Tables);
public sealed record PeerDatabaseTransaction(int Version, long Revision, string Schema, PeerRowChange[] Changes, PeerDatabaseImage? Initial = null);

/// <summary>SQLite row capture. Values generated by SQL are captured on the leader, never re-evaluated by a follower.</summary>
public sealed class PeerDatabaseSchema(DbDataSource source, string protectionKeyId = "")
{
    public static readonly HashSet<string> LocalTables = new(StringComparer.Ordinal)
        { "schema_migrations", "users", "user_sessions" };
    public PeerTable[] Tables { get; private set; } = [];
    public string Fingerprint { get; private set; } = "";
    internal static DbCommand Command(DbConnection connection, DbTransaction? transaction, string sql)
    {
        if (connection is SqliteConnectionWrapper sqlite)
        {
            var command = sqlite.Inner.CreateCommand();
            command.CommandText = sql;
            command.Transaction = (transaction as SqliteTransactionWrapper)?.Inner;
            return command;
        }
        return Sql.Command(sql, connection, transaction);
    }

    public async Task InitializeAsync(CancellationToken ct)
    {
        if (!Sql.IsSqlite(source)) throw new InvalidOperationException("La réplication de base de données prend uniquement en charge SQLite.");
        await using var connection = await source.OpenConnectionAsync(ct);
        var names = new List<string>();
        await using (var command = Command(connection, null,
            "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'"))
        await using (var rows = await command.ExecuteReaderAsync(ct))
            while (await rows.ReadAsync(ct))
            {
                var name = rows.GetString(0);
                if (!LocalTables.Contains(name) && !name.StartsWith("peer_replication_", StringComparison.Ordinal)) names.Add(name);
            }
        var tables = new List<PeerTable>();
        foreach (var name in names.Order(StringComparer.Ordinal))
        {
            ValidateIdentifier(name);
            var columns = new List<PeerColumn>();
            await using (var command = Command(connection, null,
                $"SELECT name,type,pk FROM pragma_table_xinfo('{name}') WHERE hidden=0 ORDER BY cid"))
            await using (var rows = await command.ExecuteReaderAsync(ct))
                while (await rows.ReadAsync(ct))
                    columns.Add(new PeerColumn(rows.GetString(0), rows.GetString(1).ToLowerInvariant(), Convert.ToInt32(rows.GetValue(2), CultureInfo.InvariantCulture)));
            if (!columns.Any(column => column.KeyOrder > 0))
                throw new InvalidOperationException($"La table partagée {name} doit avoir une clé primaire pour être répliquée.");
            var parents = new List<string>();
            await using (var command = Command(connection, null,
                $"SELECT DISTINCT \"table\" FROM pragma_foreign_key_list('{name}')"))
            await using (var rows = await command.ExecuteReaderAsync(ct))
                while (await rows.ReadAsync(ct)) parents.Add(rows.GetString(0));
            tables.Add(new PeerTable(name, columns.ToArray(), parents.Order(StringComparer.Ordinal).ToArray()));
        }
        var ordered = new List<PeerTable>();
        while (tables.Count > 0)
        {
            var ready = tables.Where(table => table.Parents.All(parent => parent == table.Name || tables.All(other => other.Name != parent))).ToArray();
            if (ready.Length == 0) throw new InvalidOperationException("Cycle de dépendances entre tables partagées.");
            ordered.AddRange(ready);
            foreach (var table in ready) tables.Remove(table);
        }
        Tables = ordered.ToArray();
        var migrations = new SortedDictionary<string, string?>(StringComparer.Ordinal);
        await using (var command = Command(connection, null, "SELECT version,checksum FROM schema_migrations ORDER BY version"))
        await using (var rows = await command.ExecuteReaderAsync(ct))
            while (await rows.ReadAsync(ct)) migrations.Add(rows.GetString(0), rows.IsDBNull(1) ? null : rows.GetString(1));
        Fingerprint = Convert.ToHexStringLower(SHA256.HashData(JsonSerializer.SerializeToUtf8Bytes(new { provider = "sqlite", protectionKeyId, migrations, tables = Tables })));
        await using var tx = await connection.BeginTransactionAsync(ct);
        await ExecuteAsync(connection, tx,
            """
              CREATE TABLE IF NOT EXISTS peer_replication_context(singleton INTEGER PRIMARY KEY CHECK(singleton=1),active INTEGER NOT NULL);
              INSERT OR IGNORE INTO peer_replication_context VALUES(1,0);
              CREATE TABLE IF NOT EXISTS peer_replication_changes(seq INTEGER PRIMARY KEY,table_name TEXT NOT NULL,operation TEXT NOT NULL,key_data TEXT NOT NULL,row_data TEXT);
              """, ct);
        foreach (var table in Tables)
        foreach (var operation in new[] { "INSERT", "UPDATE", "DELETE" })
        {
            var prefix = operation == "DELETE" ? "OLD" : "NEW";
            var key = JsonObject(table.Keys, operation == "INSERT" ? "NEW" : "OLD");
            var row = operation == "DELETE" ? "NULL" : JsonObject(table.Columns, prefix);
            var trigger = $"peer_capture_{table.Name}_{operation.ToLowerInvariant()}";
            var sql = $"""
                   DROP TRIGGER IF EXISTS "{trigger}";
                   CREATE TRIGGER "{trigger}" AFTER {operation} ON "{table.Name}"
                   WHEN (SELECT active FROM peer_replication_context WHERE singleton=1)=1
                   BEGIN INSERT INTO peer_replication_changes(table_name,operation,key_data,row_data)
                   VALUES('{table.Name}','{operation}',{key},{row}); END;
                   """;
            await ExecuteAsync(connection, tx, sql, ct);
        }
        await ExecuteAsync(connection, tx, "UPDATE peer_replication_context SET active=0; DELETE FROM peer_replication_changes", ct);
        await tx.CommitAsync(ct);
    }

    private string JsonObject(IEnumerable<PeerColumn> columns, string prefix) =>
        "json_object("
        + string.Join(",", columns.Select(column =>
        {
            var value = $"{prefix}.\"{column.Name}\"";
            if (column.Type == "blob")
                value = $"CASE WHEN {value} IS NULL THEN NULL ELSE hex({value}) END";
            return $"'{column.Name}',{value}";
        })) + ")";

    public async Task<PeerDatabaseImage> CaptureAsync(DbConnection connection, DbTransaction tx, long revision, CancellationToken ct)
    {
        var result = new Dictionary<string, Dictionary<string, Dictionary<string, JsonElement>>>(StringComparer.Ordinal);
        foreach (var table in Tables)
        {
            var records = new Dictionary<string, Dictionary<string, JsonElement>>(StringComparer.Ordinal);
            await using var command = Command(connection, tx, $"SELECT {JsonObject(table.Columns, "t")} FROM \"{table.Name}\" t");
            await using var reader = await command.ExecuteReaderAsync(ct);
            while (await reader.ReadAsync(ct))
            {
                var row = JsonSerializer.Deserialize<Dictionary<string, JsonElement>>(reader.GetString(0))!;
                records.Add(Key(table, row), row);
            }
            result.Add(table.Name, records);
        }
        return new PeerDatabaseImage(revision, Fingerprint, result.ToImmutableDictionary(pair => pair.Key,
            pair => pair.Value.ToImmutableDictionary(StringComparer.Ordinal), StringComparer.Ordinal));
    }

    public async Task<PeerRowChange[]> ReadChangesAsync(DbConnection connection, DbTransaction tx, CancellationToken ct)
    {
        var changes = new List<PeerRowChange>();
        await using var command = Command(connection, tx, "SELECT table_name,operation,key_data,row_data FROM peer_replication_changes ORDER BY seq");
        await using var rows = await command.ExecuteReaderAsync(ct);
        while (await rows.ReadAsync(ct))
            changes.Add(new(rows.GetString(0), rows.GetString(1),
                JsonSerializer.Deserialize<Dictionary<string, JsonElement>>(rows.GetString(2))!,
                rows.IsDBNull(3) ? null : JsonSerializer.Deserialize<Dictionary<string, JsonElement>>(rows.GetString(3))));
        foreach (var change in changes)
        {
            var table = Tables.Single(table => table.Name == change.Table);
            if (change.Row is not null && Key(table, change.Key) != Key(table, change.Row))
                throw new InvalidOperationException("Une clé primaire partagée ne peut pas être modifiée.");
        }
        return changes.ToArray();
    }

    public async Task ApplyChangesAsync(DbConnection connection, DbTransaction tx, IEnumerable<PeerRowChange> changes, CancellationToken ct)
    {
        foreach (var change in changes)
        {
            if (change.Operation is not ("INSERT" or "UPDATE" or "DELETE")) throw new InvalidDataException("Opération de réplication inconnue.");
            var table = Tables.SingleOrDefault(table => table.Name == change.Table)
                ?? throw new InvalidDataException("Table de réplication inconnue.");
            if (change.Key.Count != table.Keys.Length || table.Keys.Any(key => !change.Key.ContainsKey(key.Name)))
                throw new InvalidDataException("Clé de réplication invalide.");
            var predicate = string.Join(" AND ", table.Keys.Select(key => $"\"{key.Name}\"=@key_{key.Name}"));
            await using var command = Command(connection, tx, "");
            if (change.Operation == "DELETE")
                command.CommandText = $"DELETE FROM \"{table.Name}\" WHERE {predicate}";
            else
            {
                var row = change.Row ?? throw new InvalidDataException("Ligne de réplication absente.");
                if (row.Count != table.Columns.Length || table.Columns.Any(column => !row.ContainsKey(column.Name)))
                    throw new InvalidDataException("Colonnes de réplication incompatibles.");
                var keys = string.Join(",", table.Keys.Select(key => $"\"{key.Name}\""));
                var updates = string.Join(",", table.Columns.Where(column => column.KeyOrder == 0)
                    .Select(column => $"\"{column.Name}\"=excluded.\"{column.Name}\""));
                command.CommandText = $"INSERT INTO \"{table.Name}\"({string.Join(",", table.Columns.Select(column => $"\"{column.Name}\""))}) VALUES({string.Join(",", table.Columns.Select(column => "@value_" + column.Name))}) ON CONFLICT({keys}) "
                    + (updates.Length == 0 ? "DO NOTHING" : "DO UPDATE SET " + updates);
                foreach (var column in table.Columns) AddValue(command, "value_" + column.Name, column.Type, row[column.Name]);
            }
            if (change.Operation == "DELETE")
                foreach (var key in table.Keys) AddValue(command, "key_" + key.Name, key.Type, change.Key[key.Name]);
            await command.ExecuteNonQueryAsync(ct);
        }
    }

    public async Task RestoreAsync(DbConnection connection, DbTransaction tx, PeerDatabaseImage image, CancellationToken ct)
    {
        if (image.Schema != Fingerprint || !image.Tables.Keys.Order().SequenceEqual(Tables.Select(table => table.Name).Order()))
            throw new InvalidDataException("Le schéma de l’instantané est incompatible.");
        await ExecuteAsync(connection, tx, "PRAGMA defer_foreign_keys=ON", ct);
        foreach (var table in Tables.Reverse())
        {
            if (table.Name == "executions")
            {
                await using var prune = Command(connection, tx, "DELETE FROM executions WHERE NOT EXISTS (SELECT 1 FROM executions child WHERE child.retry_of=executions.id)");
                while (await prune.ExecuteNonQueryAsync(ct) > 0) { }
                await using var remaining = Command(connection, tx, "SELECT count(*) FROM executions");
                if (Convert.ToInt64(await remaining.ExecuteScalarAsync(ct), CultureInfo.InvariantCulture) != 0)
                    throw new InvalidDataException("Cycle de reprises dans les exécutions locales.");
                continue;
            }
            await ExecuteAsync(connection, tx, $"DELETE FROM \"{table.Name}\"", ct);
        }
        foreach (var table in Tables)
        {
            var rows = image.Tables[table.Name].Values.ToList();
            // Executions can reference an earlier execution. Insert ancestors before retries.
            if (table.Name == "executions")
            {
                var pending = rows.ToList();
                rows.Clear();
                var ids = new HashSet<string>(StringComparer.Ordinal);
                while (pending.Count > 0)
                {
                    var ready = pending.Where(row => !row.TryGetValue("retry_of", out var parent)
                        || parent.ValueKind == JsonValueKind.Null || ids.Contains(parent.GetString()!)).ToArray();
                    if (ready.Length == 0) throw new InvalidDataException("Cycle d’exécutions dans l’instantané.");
                    foreach (var row in ready) { rows.Add(row); pending.Remove(row); ids.Add(row["id"].GetString()!); }
                }
            }
            await ApplyChangesAsync(connection, tx, rows.Select(row => new PeerRowChange(table.Name, "INSERT",
                table.Keys.ToDictionary(key => key.Name, key => row[key.Name]), row)), ct);
        }
    }

    public static string Key(PeerTable table, IReadOnlyDictionary<string, JsonElement> row) =>
        JsonSerializer.Serialize(table.Keys.Select(key => row[key.Name]).ToArray());

    private void AddValue(DbCommand command, string name, string type, JsonElement value)
    {
        if (value.ValueKind == JsonValueKind.Null)
        {
            command.Parameters.AddWithValue(name, DBNull.Value);
            return;
        }
        object parsed = type switch
        {
            "blob" => Convert.FromHexString(value.GetString()!),
            "uuid" => Guid.Parse(value.GetString()!),
            "bool" or "boolean" => value.ValueKind == JsonValueKind.True || (value.ValueKind == JsonValueKind.Number && Convert.ToDouble(JsonNumber(value), CultureInfo.InvariantCulture) != 0),
            "json" => value.GetRawText(),
            "timestamp" => value.GetString() switch
            {
                "infinity" => DateTime.MaxValue,
                "-infinity" => DateTime.MinValue,
                var text => DateTime.Parse(text!, CultureInfo.InvariantCulture, DateTimeStyles.AdjustToUniversal | DateTimeStyles.AssumeUniversal)
            },
            "smallint" or "integer" or "bigint" or "numeric" or "real" or "double" => JsonNumber(value),
            _ => value.ValueKind switch { JsonValueKind.Number => value.TryGetInt64(out var number) ? (object)number : value.GetDecimal(), JsonValueKind.True => true, JsonValueKind.False => false, _ => value.GetString()! }
        };
        parsed = SqliteCommandWrapper.Convert(parsed);
        command.Parameters.AddWithValue(name, parsed);
    }

    public static async Task ExecuteAsync(DbConnection connection, DbTransaction tx, string sql, CancellationToken ct)
    {
        await using var command = Command(connection, tx, sql);
        await command.ExecuteNonQueryAsync(ct);
    }

    private static object JsonNumber(JsonElement value) => value.TryGetInt64(out var integer) ? integer
        : value.TryGetDecimal(out var decimalValue) ? decimalValue
        : value.GetDouble();

    private static void ValidateIdentifier(string name)
    {
        if (name.Length == 0 || name.Any(character => !char.IsAsciiLetterOrDigit(character) && character != '_'))
            throw new InvalidDataException("Identifiant SQL inattendu.");
    }
}
